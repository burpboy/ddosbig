#!/bin/bash

# BrutalDDoS Kill Script
# Kills all running brutaldDos processes and cleans up artifacts.

set -e

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BINARY_NAME="brutaldDos"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

echo -e "${YELLOW}[Cleanup]${NC} Searching for running $BINARY_NAME processes..."

# Find PIDs of the specific binary
PIDS=$(pgrep -f "$BINARY_NAME" 2>/dev/null || true)

if [ -z "$PIDS" ]; then
    echo -e "${GREEN}[INFO]${NC} No running instances of $BINARY_NAME found."
else
    echo -e "${RED}[Killing]${NC} Processes: $PIDS"
    
    # Send SIGTERM first for graceful shutdown
    kill -TERM $PIDS 2>/dev/null || true
    
    # Wait briefly for graceful exit
    sleep 2
    
    # Force kill if still alive
    STILL_ALIVE=$(pgrep -f "$BINARY_NAME" 2>/dev/null || true)
    if [ -n "$STILL_ALIVE" ]; then
        echo -e "${RED}[Force Killing]${NC} Processes: $STILL_ALIVE"
        kill -9 $STILL_ALIVE 2>/dev/null || true
    fi
fi

# Clean up benchmark logs and other temp files generated by scripts
echo -e "${GREEN}[Cleanup]${NC} Removing temporary benchmark logs..."
rm -f "$PROJECT_ROOT/benchmark_log.txt"
rm -f "$PROJECT_ROOT/*.log"

# Optional: Clean up build directory if disk space is low (commented out by default)
# rm -rf "$PROJECT_ROOT/build"

echo -e "${GREEN}[DONE]${NC} Cleanup complete."
